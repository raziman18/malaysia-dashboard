// Turns DOSM's state boundaries into SVG paths for the state map (src/lib/state-shapes.ts).
// Source: https://raw.githubusercontent.com/dosm-malaysia/data-open/main/datasets/geodata/administrative_1_state.geojson
// (DOSM Open Data Licence), simplified first with:
//   npx -y mapshaper administrative_1_state.geojson -simplify 10% keep-shapes -o precision=0.001 states.geojson
// Usage: node scripts/build-state-shapes.mjs states.geojson
import { readFileSync, writeFileSync } from "node:fs";

const scale = 60; // SVG units per degree
const west = 99.6;
const north = 7.4;
// Sabah, Sarawak and Labuan are drawn 4 degrees further west so the map fits a phone screen.
const borneoShift = 4;
const borneo = new Set(["Sabah", "Sarawak", "W.P. Labuan"]);

const { features } = JSON.parse(readFileSync(process.argv[2], "utf8"));
let width = 0;
let height = 0;
const shapes = features.map(({ properties, geometry }) => {
  const shift = borneo.has(properties.state) ? borneoShift : 0;
  const polygons = geometry.type === "MultiPolygon" ? geometry.coordinates : [geometry.coordinates];
  const d = polygons
    .flat()
    .map((ring) =>
      ring
        .map(([lon, lat], index) => {
          const x = (lon - shift - west) * scale;
          const y = (north - lat) * scale;
          width = Math.max(width, x);
          height = Math.max(height, y);
          return `${index ? "L" : "M"}${x.toFixed(1)},${y.toFixed(1)}`;
        })
        .join("") + "Z",
    )
    .join("");
  return { state: properties.state, d };
});

const body = shapes.map((shape) => `  { state: ${JSON.stringify(shape.state)}, d: ${JSON.stringify(shape.d)} },`).join("\n");
writeFileSync(
  "src/lib/state-shapes.ts",
  `// Generated by scripts/build-state-shapes.mjs from DOSM's state boundaries (DOSM Open Data Licence). Do not edit.\nexport const mapSize = { width: ${Math.ceil(width)}, height: ${Math.ceil(height)} };\n\nexport const stateShapes: { state: string; d: string }[] = [\n${body}\n];\n`,
);
console.log(shapes.length, "states", Math.ceil(width), "x", Math.ceil(height));
